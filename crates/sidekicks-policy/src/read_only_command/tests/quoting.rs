//! Quoting and expansion, by the word's position.

use rstest::rstest;

use super::reads_only;

#[rstest]
#[case::dquote_ls_dquote_la("\"ls\" -la", true)]
#[case::squote_ls_squote_la("'ls' -la", true)]
#[case::l_backslash_s_la("l\\s -la", true)]
#[case::dollar_squote_ls_squote_la("$'ls' -la", true)]
#[case::l_dquote_s_dquote_la("l\"s\" -la", true)]
#[case::dollar_x_la("$x -la", false)]
#[case::dollar_brace_x_la("${x} -la", false)]
#[case::dollar_paren_echo_ls_la("$(echo ls) -la", false)]
#[case::backquote_echo_ls_backquote_la("`echo ls` -la", false)]
#[case::l_question_la("l? -la", false)]
#[case::bracket_l_s_la("[l]s -la", false)]
#[case::l_backslash_newline_s_la("l\\\ns -la", true)]
#[case::dollar_dquote_cat_dquote_a_txt("$\"cat\" a.txt", false)]
#[case::rg_dquote_pre_eq_sh_dquote_foo("rg \"--pre=sh\" foo", false)]
#[case::rg_squote_pre_eq_sh_squote_foo("rg '--pre=sh' foo", false)]
#[case::rg_backslash_pre_eq_sh_foo("rg -\\-pre=sh foo", false)]
#[case::rg_dollar_squote_pre_eq_sh_squote_foo("rg $'--pre=sh' foo", false)]
#[case::rg_dollar_squote_backslash_x2d_pre_eq_sh("rg $'\\x2d-pre=sh' foo", false)]
#[case::rg_dollar_x_foo("rg $x foo", false)]
#[case::rg_dollar_brace_x_foo("rg ${x} foo", false)]
#[case::rg_dollar_paren_echo_i_foo("rg $(echo -i) foo", false)]
#[case::rg_backquote_echo_i_backquote_foo("rg `echo -i` foo", false)]
#[case::rg_star_foo("rg -* foo", false)]
#[case::rg_backslash_newline_pre_eq_sh("rg --\\\npre=sh .", false)]
// zsh drops the backslash of an escape it does not know inside `$'…'`, bash keeps it.
#[case::rg_dollar_squote_unknown_escapes(r"rg $'\-\-pre=sh' foo", false)]
#[case::find_dollar_squote_unknown_escape(r"find sub $'\-delete'", false)]
#[case::rg_e_carriage_return_pre_eq_sh("rg -e\r --pre=sh .", false)]
#[case::rg_e_foo("rg -e foo .", true)]
#[case::rg_e_dquote_dollar_x_dquote("rg -e \"$x\" .", false)]
#[case::rg_e_dollar_x("rg -e $x .", false)]
#[case::rg_e_dollar_brace_x("rg -e ${x} .", false)]
#[case::rg_e_dollar_paren_echo_a("rg -e $(echo a) .", false)]
#[case::rg_e_backquote_echo_a_backquote("rg -e `echo a` .", false)]
#[case::rg_e_dollar_squote_a_backslash_tb_squote("rg -e $'a\\tb' .", true)]
#[case::rg_f_tilde_patterns_txt_foo("rg -f ~/patterns.txt foo", true)]
#[case::head_n_dollar_brace_n_a_txt("head -n ${n} a.txt", true)]
#[case::rg_e_squote_star_rs_squote("rg -e '*.rs' .", true)]
#[case::rg_g_star_rs_foo("rg -g *.rs foo", false)]
#[case::rg_e_backslash_x("rg -e \\-x .", true)]
#[case::head_n_dollar_n_a_txt("head -n $n a.txt", true)]
#[case::find_name_star("find . -name -*", false)]
#[case::rg_e_star("rg -e -* .", false)]
#[case::git_log_author_star("git log --author -*", false)]
#[case::find_name_x_star("find . -name x*", false)]
#[case::cat_dollar_x("cat $x", true)]
#[case::cat_dquote_dollar_x_dquote("cat \"$x\"", true)]
#[case::cat_dollar_brace_x_colon_a_txt("cat ${x:-a.txt}", true)]
#[case::cat_dollar_paren_ls("cat $(ls)", true)]
#[case::cat_tilde_a_txt("cat ~/a.txt", true)]
#[case::ls_star_ts("ls *.ts", true)]
#[case::wc_l_src_star_py("wc -l src/*.py", true)]
#[case::cat_brace_a_comma_b_txt("cat {a,b}.txt", true)]
#[case::rg_foo_star_rs("rg foo *.rs", false)]
#[case::rg_foo_dollar_x("rg foo $x", false)]
#[case::rg_foo_src_star_rs("rg foo src/*.rs", false)]
#[case::find_src_star_name_x("find src/* -name x", false)]
#[case::git_log_double_dash_src_star_rs("git log -- src/*.rs", false)]
#[case::find_name_star_rs("find . -name *.rs", false)]
#[case::cat_a_backslash_b_txt("cat a\\ b.txt", true)]
#[case::cat_dollar_squote_a_backslash_nb_squote("cat $'a\\nb'", true)]
#[case::cat_dquote_a_b_dquote("cat \"a b\"", true)]
#[case::rg_foo_tilde("rg foo ~", true)]
fn a_word_reads_only_as_the_shell_passes_it(#[case] line: &str, #[case] is_read_only: bool) {
    assert_eq!(reads_only(line), is_read_only, "{line:?}");
}
