// A wrapper whose own words use up the command is its program, as `sudo -s` runs a shell that
// reads the pipe.
#[case::shell_through_a_wrapper("echo x | sudo -s", false)]
fn a_wrapper_reads_only_when_it_is_a_reading_one(#[case] line: &str, #[case] is_read_only: bool) {
    assert_eq!(reads_only(line), is_read_only, "{line:?}");
}
