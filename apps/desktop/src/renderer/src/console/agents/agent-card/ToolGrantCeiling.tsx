// The ceiling a tool allowlist cannot raise, said once for the whole roster.
//
// A NODE-WIDE FACT, SO NOT A LINE ON A CARD. The per-agent allowlist belongs on the
// card and the node-wide switch on the browser settings page, and this states how the
// two compose. It was written under every card, which repeated three lines per agent
// and — under the position where the roster reply carried no configuration at all —
// asserted that an allowlist had been applied to a reply that named none.
//
// SO THE SUBJECT IS THE MECHANISM AND NEVER THIS AGENT. "A tool allowlist is applied
// at spawn" is true of every spawn on this node, including the ones nobody has made
// yet; "applied at spawn" with an agent as its implied subject was a claim about a
// particular attach, and the card is where a claim about a particular attach belongs.
//
// IT IS NOT A CONTROL AND OFFERS NONE. The switch it names lives on the browser
// settings page, and a second control for it here would be a second answer to a
// node-wide setting.

/** The ceiling, once, above a roster that has at least one agent to state it about. */
export function ToolGrantCeiling(): React.JSX.Element {
  return (
    <p className="meridian-agents__grant-note">
      A tool allowlist is applied at spawn and filters the browser page tool set like any other
      source; a node-wide switch on the browser settings page withholds those tools from every later
      spawn here, and an allowlist cannot turn them back on.
    </p>
  );
}
