// ITS OWN MODULE BECAUSE TWO SURFACES READ IT. `RunPhaseGraph.tsx` labels a node and
// `RunParks.tsx` captions a card, and the whole value of the constant is that the two
// move together — a copy in each file is the second declaration of one closed answer
// that `apps/desktop/AGENTS.md` rejects, and the day a definition read lands it is the
// copy nobody remembers to change.

/**
 * `undefined` RATHER THAN THE PHASE ID, which is the decision the constant records.
 *
 * Both surfaces name a phase, and both used to be handed the phase id through a
 * function called a display label. That put an opaque wire key on screen in the face
 * and weight an authored name would have had, so a reader could not tell a chosen
 * name from a generated one, which is the single fact this pane is otherwise
 * scrupulous about rendering the absence of.
 *
 * Both surfaces now take the name and the identifier as two values: the identifier
 * always, in the mono provenance signature `Spec-023 §Console Design (Meridian)`
 * rule 4 gives a wire-true figure, and the name only where there is one. There is
 * none here because the authored name lives on the definition body and no read
 * reachable from this build serves it (`RunPhaseGraph.tsx` enumerates why), and this
 * is the one place that says so — the day a definition read lands, its `name`
 * replaces this constant and both surfaces move with it.
 */
export const PHASE_DISPLAY_NAME: string | undefined = undefined;
